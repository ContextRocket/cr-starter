#!/usr/bin/env node

/**
 * Generate the small pieces of i18n wiring that must know the complete
 * message tree.
 *
 * Message files are the source of truth. A fork can add a locale barrel or a
 * module under i18n/messages without editing registry.ts, register-server.ts,
 * locale-provider.tsx, or the module barrels. Run this script before dev,
 * typecheck, test, and build (the package scripts wire it in).
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const messagesDir = path.resolve(scriptDir, "../i18n/messages");
const i18nDir = path.resolve(messagesDir, "..");

const LOCALE_FILE_RE = /^([a-z]{2,3}(?:-[A-Z][a-z]{2})?)\.ts$/;

function localeFiles() {
  return fs
    .readdirSync(messagesDir)
    .map((name) => {
      const match = name.match(LOCALE_FILE_RE);
      return match ? match[1] : null;
    })
    .filter(Boolean)
    .sort();
}

function moduleDirectories() {
  return fs
    .readdirSync(path.join(messagesDir, "modules"), { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

function exportedConstant(filePath) {
  const source = fs.readFileSync(filePath, "utf8");
  const match = source.match(
    /export\s+const\s+([A-Za-z_$][\w$]*)(?:\s*:[^=]+)?\s*=/,
  );
  if (!match) {
    throw new Error(`No exported const found in ${filePath}`);
  }
  return match[1];
}

function writeIfChanged(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  const previous = fs.existsSync(filePath)
    ? fs.readFileSync(filePath, "utf8")
    : null;
  if (previous !== content) {
    fs.writeFileSync(filePath, content);
  }
}

/**
 * Emit an object-literal KEY the way Prettier (quoteProps: "as-needed") would:
 * bare when the locale is a valid JS identifier (en, es, zh), quoted only when
 * it is not (zh-Hans, pt-BR). This keeps generated files byte-identical across
 * forks whether or not a fork runs Prettier over generated output on commit.
 */
function objectKey(key) {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
}

/**
 * Emit an object literal body the way Prettier would: `{}` when there are no
 * entries (a single-locale / en-only fork), else the multi-line form. Without
 * this an empty object serializes as `{\n\n}`, which Prettier rewrites to `{}`
 * -- a spurious diff on every commit in any fork that formats generated files.
 */
function braced(body) {
  return body ? `{\n${body}\n}` : "{}";
}

function labelName(locale) {
  const known = {
    de: "German",
    en: "English",
    es: "Spanish",
    fr: "French",
    it: "Italian",
    ja: "Japanese",
    ko: "Korean",
    nl: "Dutch",
    pt: "Portuguese",
    zh: "Chinese",
  };
  if (known[locale]) return known[locale];
  return locale
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function moduleBarrel(locale) {
  const modulesDir = path.join(messagesDir, "modules");
  const imports = [];
  const spreads = [];

  for (const moduleName of moduleDirectories()) {
    const moduleFile = path.join(modulesDir, moduleName, `${locale}.ts`);
    if (!fs.existsSync(moduleFile)) continue;
    const exported = exportedConstant(moduleFile);
    imports.push(`import { ${exported} } from "./${moduleName}/${locale}";`);
    spreads.push(`  ...${exported},`);
  }

  // Omit the import block entirely when a locale has no module surfaces, so an
  // empty barrel doesn't serialize with the extra blank lines Prettier strips.
  const importBlock = imports.length ? `${imports.join("\n")}\n\n` : "";
  return `/**\n * GENERATED by scripts/generate-i18n-registry.mjs.\n *\n * Add a message surface under modules/<surface>/${locale}.ts; do not edit\n * this barrel by hand. The source module remains fork-owned when applicable.\n */\n\n${importBlock}export const modules${locale.charAt(0).toUpperCase() + locale.slice(1).replaceAll("-", "")} = ${braced(spreads.join("\n"))} as const;\n`;
}

function registryFile(locales) {
  const labels = locales
    .map(
      (locale) =>
        `  ${objectKey(locale)}: ${JSON.stringify(`locale.label${labelName(locale)}`)},`,
    )
    .join("\n");
  return `/**\n * Locale message registry -- GENERATED by scripts/generate-i18n-registry.mjs.\n * Do not edit by hand; add a ${"<locale>"}.ts barrel in i18n/messages/ and\n * re-run the generator.\n *\n * This file is client-safe: it carries only locale metadata, never message\n * trees.\n */\n\nexport const SUPPORTED_LOCALES = [${locales.map((locale) => JSON.stringify(locale)).join(", ")}] as const;\nexport type SupportedLocale = (typeof SUPPORTED_LOCALES)[number];\n\n/** Conventional translated labels in the shared locale slice. */\nexport const LOCALE_LABEL_PATHS: Record<SupportedLocale, string> = {\n${labels}\n};\n`;
}

function serverRegistration(locales) {
  const loaders = locales
    .filter((locale) => locale !== "en")
    .map(
      (locale) =>
        `  ${objectKey(locale)}: async () =>\n    (await import("./${locale}")).${locale} as unknown as Record<string, unknown>,`,
    )
    .join("\n");
  return `/**\n * Server-only locale registration -- GENERATED by\n * scripts/generate-i18n-registry.mjs.\n *\n * English is bundled eagerly (the fallback tree and the source of the \`Path\`\n * type). Non-en trees are loaded + registered LAZILY via explicit dynamic\n * import, so an inactive language is never compiled into the server graph -- a\n * narrowed dev build (\`NEXT_PUBLIC_CR_UI_LOCALES\`) compiles only the locales it\n * actually renders. This module must NEVER appear in the client bundle; the\n * \`import "server-only"\` guard enforces that.\n *\n * \`getServerLocaleTree\` (async) lets the [locale] layout register + pass the\n * active locale's tree to LocaleProvider (RSC payload injection). The layout\n * awaits it before rendering children, so every server \`t()\` under it resolves\n * from the registered active-locale tree.\n */\n\nimport "server-only";\nimport { en } from "./en";\nimport { registerLocaleMessages } from "../keys";\nimport type { SupportedLocale } from "./registry";\n\n// English is always present: register it once at module init (server-side).\nregisterLocaleMessages("en", en as unknown as Record<string, unknown>);\n\n// Non-en trees: explicit per-locale dynamic import (NOT a computed specifier,\n// which would build a directory request-context) so each is its own chunk and\n// only compiled when actually requested.\nconst NON_EN_LOADERS: Partial<\n  Record<SupportedLocale, () => Promise<Record<string, unknown>>>\n> = ${braced(loaders)};\n\nconst _registered = new Set<SupportedLocale>(["en"]);\n\n/**\n * Ensure the given locale's tree is registered in the server-side keys.ts\n * registry, and return it for RSC-payload injection. Returns null for en (the\n * English tree is always bundled client-side as the fallback).\n */\nexport async function getServerLocaleTree(\n  locale: SupportedLocale,\n): Promise<Record<string, unknown> | null> {\n  if (locale === "en") return null;\n  // Cast: in a single-locale (en-only) build \`locale\` narrows to \`never\` after\n  // the guard above, which would make this index access non-callable.\n  const load = NON_EN_LOADERS[locale as SupportedLocale];\n  if (!load) return null;\n  const tree = await load();\n  if (!_registered.has(locale)) {\n    registerLocaleMessages(locale, tree);\n    _registered.add(locale);\n  }\n  return tree;\n}\n`;
}

function clientLoaders(locales) {
  const nonEnglish = locales.filter((locale) => locale !== "en");
  const entries = nonEnglish
    .map(
      (locale) =>
        `  ${objectKey(locale)}: () =>\n    import("./messages/${locale}").then((m) => m.${locale} as Record<string, unknown>),`,
    )
    .join("\n");
  return `/**\n * Client locale loaders -- GENERATED by\n * scripts/generate-i18n-registry.mjs.\n *\n * This is intentionally an explicit import map. A computed import over the\n * messages directory can pull server-only registration into the client\n * bundle.\n */\n\nimport type { SupportedLocale } from "./messages/registry";\n\nexport type LocaleLoader = () => Promise<Record<string, unknown>>;\n\nexport const CLIENT_LOCALE_LOADERS: Partial<\n  Record<SupportedLocale, LocaleLoader>\n> = ${braced(entries)};\n`;
}

function siteContentSlices(locales) {
  const imports = [];
  const entries = [];

  for (const locale of locales) {
    const filePath = path.join(messagesDir, "site", locale + ".ts");
    if (!fs.existsSync(filePath)) continue;
    const exported = exportedConstant(filePath);
    imports.push(
      "import { " + exported + ' } from "./messages/site/' + locale + '";',
    );
    entries.push(
      "  " +
        objectKey(locale) +
        ": " +
        exported +
        " as unknown as Record<string, unknown>,",
    );
  }

  return [
    "/**",
    " * Site message slices -- GENERATED by scripts/generate-i18n-registry.mjs.",
    " *",
    " * The site-content adapter imports this map instead of hard-coding a fixed",
    " * set of languages. A single-language fork therefore ships only its own",
    " * site message bundle.",
    " */",
    "",
    imports.join("\n"),
    "",
    "export const SITE_MESSAGE_SLICES: Record<string, Record<string, unknown>> = " +
      braced(entries.join("\n")) +
      ";",
    "",
  ].join("\n");
}

function testFixtures(locales) {
  const imports = [];
  const trees = [];
  const slices = [];

  for (const locale of locales) {
    const rootPath = path.join(messagesDir, locale + ".ts");
    const rootExport = exportedConstant(rootPath);
    imports.push("import { " + rootExport + ' } from "./' + locale + '";');
    const domainImports = [];
    for (const domain of ["shared", "app", "site"]) {
      const domainPath = path.join(messagesDir, domain, locale + ".ts");
      if (!fs.existsSync(domainPath)) continue;
      const domainExport = exportedConstant(domainPath);
      domainImports.push({ domain, domainExport });
      imports.push(
        "import { " +
          domainExport +
          ' } from "./' +
          domain +
          "/" +
          locale +
          '";',
      );
    }
    trees.push("  " + objectKey(locale) + ": " + rootExport + ",");
    slices.push(
      "  " +
        objectKey(locale) +
        ": {\n" +
        "    merged: " +
        rootExport +
        ",\n" +
        domainImports
          .map(
            ({ domain, domainExport }) =>
              "    " + domain + ": " + domainExport + ",",
          )
          .join("\n") +
        "\n  },",
    );
  }

  return [
    "/**",
    " * i18n test fixtures -- GENERATED by scripts/generate-i18n-registry.mjs.",
    " *",
    " * Keeping these imports generated lets the shared tests exercise every",
    " * configured locale while allowing a fork to remove unused locale bundles.",
    " */",
    "",
    imports.join("\n"),
    "",
    "export const LOCALE_MESSAGE_TREES = {",
    trees.join("\n"),
    "} as const;",
    "",
    "export const LOCALE_MESSAGE_SLICES = {",
    slices.join("\n"),
    "} as const;",
    "",
  ].join("\n");
}

const locales = localeFiles();
if (!locales.includes("en")) {
  throw new Error(
    `Expected i18n/messages/en.ts; found locales: ${locales.join(", ")}`,
  );
}

const modulesDir = path.join(messagesDir, "modules");
for (const name of fs.readdirSync(modulesDir)) {
  if (!/^([a-z]{2,3}(?:-[A-Z][a-z]{2})?)\.ts$/.test(name)) continue;
  const locale = name.slice(0, -3);
  if (!locales.includes(locale)) fs.unlinkSync(path.join(modulesDir, name));
}
for (const locale of locales) {
  writeIfChanged(path.join(modulesDir, `${locale}.ts`), moduleBarrel(locale));
}

writeIfChanged(path.join(messagesDir, "registry.ts"), registryFile(locales));
writeIfChanged(
  path.join(messagesDir, "register-server.ts"),
  serverRegistration(locales),
);
writeIfChanged(path.join(i18nDir, "locale-loaders.ts"), clientLoaders(locales));
writeIfChanged(
  path.join(i18nDir, "site-content-slices.ts"),
  siteContentSlices(locales),
);
writeIfChanged(
  path.join(messagesDir, "test-fixtures.ts"),
  testFixtures(locales),
);

console.log(`Generated i18n wiring for ${locales.join(", ")}.`);
