#!/usr/bin/env node

/**
 * Generate the small pieces of i18n wiring that must know the complete
 * message tree.
 *
 * Message files are the source of truth. A fork can add a locale barrel or a
 * module under i18n/messages without editing registry.ts, register-server.ts,
 * locale-provider.tsx, or the module barrels. Run this script before dev,
 * typecheck, test, and build (the package scripts wire it in).
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const messagesDir = path.resolve(scriptDir, "../i18n/messages");
const i18nDir = path.resolve(messagesDir, "..");

const LOCALE_FILE_RE = /^([a-z]{2,3}(?:-[A-Z][a-z]{2})?)\.ts$/;

function localeFiles() {
  return fs
    .readdirSync(messagesDir)
    .map((name) => {
      const match = name.match(LOCALE_FILE_RE);
      return match ? match[1] : null;
    })
    .filter(Boolean)
    .sort();
}

function moduleDirectories() {
  return fs
    .readdirSync(path.join(messagesDir, "modules"), { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

function exportedConstant(filePath) {
  const source = fs.readFileSync(filePath, "utf8");
  const match = source.match(/export\s+const\s+([A-Za-z_$][\w$]*)(?:\s*:[^=]+)?\s*=/);
  if (!match) {
    throw new Error(`No exported const found in ${filePath}`);
  }
  return match[1];
}

function writeIfChanged(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  const previous = fs.existsSync(filePath)
    ? fs.readFileSync(filePath, "utf8")
    : null;
  if (previous !== content) {
    fs.writeFileSync(filePath, content);
  }
}

function labelName(locale) {
  const known = {
    de: "German",
    en: "English",
    es: "Spanish",
    fr: "French",
    it: "Italian",
    ja: "Japanese",
    ko: "Korean",
    nl: "Dutch",
    pt: "Portuguese",
    zh: "Chinese",
  };
  if (known[locale]) return known[locale];
  return locale
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function moduleBarrel(locale) {
  const modulesDir = path.join(messagesDir, "modules");
  const imports = [];
  const spreads = [];

  for (const moduleName of moduleDirectories()) {
    const moduleFile = path.join(modulesDir, moduleName, `${locale}.ts`);
    if (!fs.existsSync(moduleFile)) continue;
    const exported = exportedConstant(moduleFile);
    imports.push(`import { ${exported} } from "./${moduleName}/${locale}";`);
    spreads.push(`  ...${exported},`);
  }

  return `/**\n * GENERATED by scripts/generate-i18n-registry.mjs.\n *\n * Add a message surface under modules/<surface>/${locale}.ts; do not edit\n * this barrel by hand. The source module remains fork-owned when applicable.\n */\n\n${imports.join("\n")}\n\nexport const modules${locale.charAt(0).toUpperCase() + locale.slice(1).replaceAll("-", "")} = {\n${spreads.join("\n")}\n} as const;\n`;
}

function registryFile(locales) {
  const labels = locales
    .map((locale) => `  ${JSON.stringify(locale)}: ${JSON.stringify(`locale.label${labelName(locale)}`)},`)
    .join("\n");
  return `/**\n * Locale message registry -- GENERATED by scripts/generate-i18n-registry.mjs.\n * Do not edit by hand; add a ${"<locale>"}.ts barrel in i18n/messages/ and\n * re-run the generator.\n *\n * This file is client-safe: it carries only locale metadata, never message\n * trees.\n */\n\nexport const SUPPORTED_LOCALES = ${JSON.stringify(locales)} as const;\nexport type SupportedLocale = (typeof SUPPORTED_LOCALES)[number];\n\n/** Conventional translated labels in the shared locale slice. */\nexport const LOCALE_LABEL_PATHS: Record<SupportedLocale, string> = {\n${labels}\n};\n`;
}

function serverRegistration(locales) {
  const imports = locales.map((locale) => `import { ${locale} } from "./${locale}";`).join("\n");
  const registrations = locales
    .map((locale) => `registerLocaleMessages(${JSON.stringify(locale)}, ${locale} as unknown as Record<string, unknown>);`)
    .join("\n");
  const trees = locales
    .filter((locale) => locale !== "en")
    .map((locale) => `    ${JSON.stringify(locale)}: ${locale} as unknown as Record<string, unknown>,`)
    .join("\n");
  return `/**\n * Server-only locale registration -- GENERATED by\n * scripts/generate-i18n-registry.mjs.\n *\n * Keep this file generated: the complete set of locale trees is discovered\n * from i18n/messages/<locale>.ts so forks can add locales without changing\n * starter-owned runtime wiring.\n */\n\nimport "server-only";\n\n${imports}\nimport { registerLocaleMessages } from "../keys";\nimport type { SupportedLocale } from "./registry";\n\n${registrations}\n\nexport function getServerLocaleTree(\n  locale: SupportedLocale,\n): Record<string, unknown> | null {\n  if (locale === "en") return null;\n  const trees: Partial<Record<SupportedLocale, Record<string, unknown>>> = {\n${trees}\n  };\n  return trees[locale] ?? null;\n}\n`;
}

function clientLoaders(locales) {
  const nonEnglish = locales.filter((locale) => locale !== "en");
  const entries = nonEnglish
    .map(
      (locale) =>
        `  ${JSON.stringify(locale)}: () => import("./messages/${locale}").then((m) => m.${locale} as Record<string, unknown>),`,
    )
    .join("\n");
  return `/**\n * Client locale loaders -- GENERATED by\n * scripts/generate-i18n-registry.mjs.\n *\n * This is intentionally an explicit import map. A computed import over the\n * messages directory can pull server-only registration into the client\n * bundle.\n */\n\nimport type { SupportedLocale } from "./messages/registry";\n\nexport type LocaleLoader = () => Promise<Record<string, unknown>>;\n\nexport const CLIENT_LOCALE_LOADERS: Partial<\n  Record<SupportedLocale, LocaleLoader>\n> = {\n${entries}\n};\n`;
}

function siteContentSlices(locales) {
  const imports = [];
  const entries = [];

  for (const locale of locales) {
    const filePath = path.join(messagesDir, "site", locale + ".ts");
    if (!fs.existsSync(filePath)) continue;
    const exported = exportedConstant(filePath);
    imports.push('import { ' + exported + ' } from "./messages/site/' + locale + '";');
    entries.push('  ' + JSON.stringify(locale) + ': ' + exported + ' as unknown as Record<string, unknown>,');
  }

  return [
    "/**",
    " * Site message slices -- GENERATED by scripts/generate-i18n-registry.mjs.",
    " *",
    " * The site-content adapter imports this map instead of hard-coding a fixed",
    " * set of languages. A single-language fork therefore ships only its own",
    " * site message bundle.",
    " */",
    "",
    imports.join("\n"),
    "",
    "export const SITE_MESSAGE_SLICES: Record<string, Record<string, unknown>> = {",
    entries.join("\n"),
    "};",
    "",
  ].join("\n");
}

function testFixtures(locales) {
  const imports = [];
  const trees = [];
  const slices = [];

  for (const locale of locales) {
    const rootPath = path.join(messagesDir, locale + ".ts");
    const rootExport = exportedConstant(rootPath);
    imports.push('import { ' + rootExport + ' } from "./' + locale + '";');
    const domainImports = [];
    for (const domain of ["shared", "app", "site"]) {
      const domainPath = path.join(messagesDir, domain, locale + ".ts");
      if (!fs.existsSync(domainPath)) continue;
      const domainExport = exportedConstant(domainPath);
      domainImports.push({ domain, domainExport });
      imports.push('import { ' + domainExport + ' } from "./' + domain + '/' + locale + '";');
    }
    trees.push('  ' + JSON.stringify(locale) + ': ' + rootExport + ',');
    slices.push(
      '  ' + JSON.stringify(locale) + ': {\n' +
        '    merged: ' + rootExport + ',\n' +
        domainImports.map(({ domain, domainExport }) => '    ' + domain + ': ' + domainExport + ',').join("\n") +
        '\n  },',
    );
  }

  return [
    "/**",
    " * i18n test fixtures -- GENERATED by scripts/generate-i18n-registry.mjs.",
    " *",
    " * Keeping these imports generated lets the shared tests exercise every",
    " * configured locale while allowing a fork to remove unused locale bundles.",
    " */",
    "",
    imports.join("\n"),
    "",
    "export const LOCALE_MESSAGE_TREES = {",
    trees.join("\n"),
    "} as const;",
    "",
    "export const LOCALE_MESSAGE_SLICES = {",
    slices.join("\n"),
    "} as const;",
    "",
  ].join("\n");
}

const locales = localeFiles();
if (!locales.includes("en")) {
  throw new Error(`Expected i18n/messages/en.ts; found locales: ${locales.join(", ")}`);
}

const modulesDir = path.join(messagesDir, "modules");
for (const name of fs.readdirSync(modulesDir)) {
  if (!/^([a-z]{2,3}(?:-[A-Z][a-z]{2})?)\.ts$/.test(name)) continue;
  const locale = name.slice(0, -3);
  if (!locales.includes(locale)) fs.unlinkSync(path.join(modulesDir, name));
}
for (const locale of locales) {
  writeIfChanged(path.join(modulesDir, `${locale}.ts`), moduleBarrel(locale));
}

writeIfChanged(path.join(messagesDir, "registry.ts"), registryFile(locales));
writeIfChanged(path.join(messagesDir, "register-server.ts"), serverRegistration(locales));
writeIfChanged(path.join(i18nDir, "locale-loaders.ts"), clientLoaders(locales));
writeIfChanged(path.join(i18nDir, "site-content-slices.ts"), siteContentSlices(locales));
writeIfChanged(path.join(messagesDir, "test-fixtures.ts"), testFixtures(locales));

console.log(`Generated i18n wiring for ${locales.join(", ")}.`);
